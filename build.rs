// Build script: daftarkan 151 sprite Pokemon (assets/pokemon/<id>.png)
// sebagai include_bytes! agar terbundel di dalam binary — tanpa baca file saat runtime.
use std::{env, fs, path::PathBuf};

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let assets = manifest.join("assets").join("pokemon");
    let mut entries: Vec<(u32, PathBuf)> = Vec::new();
    for entry in fs::read_dir(&assets).expect("assets/pokemon tidak ditemukan") {
        let entry = entry.unwrap();
        let name = entry.file_name().to_string_lossy().to_string();
        if let Some(id) = name.strip_suffix(".png") {
            if let Ok(id) = id.parse::<u32>() {
                entries.push((id, entry.path()));
            }
        }
    }
    entries.sort();
    assert_eq!(entries.len(), 151, "sprite Pokemon harus tepat 151, dapat {}", entries.len());
    assert_eq!(entries.first().unwrap().0, 1);
    assert_eq!(entries.last().unwrap().0, 151);

    let mut out = String::from("// Generated by build.rs — sprite Pokemon Gen 1 (id, bytes PNG).\n");
    out.push_str("pub static SPRITES: &[(u32, &[u8])] = &[\n");
    for (id, path) in &entries {
        out.push_str(&format!(
            "    ({}, include_bytes!({:?})),\n",
            id,
            path.to_string_lossy()
        ));
    }
    out.push_str("];\n");

    let out_path = PathBuf::from(env::var("OUT_DIR").unwrap()).join("sprites.rs");
    fs::write(&out_path, out).unwrap();
    println!("cargo:rerun-if-changed=assets/pokemon");
}
