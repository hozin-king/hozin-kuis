#!/usr/bin/env python3
"""Generate src/questions_data.rs and src/pokemon_data.rs for Hozin Kuis v2.0.
Source of truth: assets/questions.json + /tmp/poke/detail/*.json (PokeAPI).
Run once at dev time; generated .rs files are checked into the repo.
"""
import json, os, sys

ROOT = os.path.expanduser("~/workspace/hozin-kuis-v2")
TYPE_ID = {
    "normal": "Normal", "fire": "Api", "water": "Air", "electric": "Listrik",
    "grass": "Rumput", "ice": "Es", "fighting": "Petarung", "poison": "Racun",
    "ground": "Tanah", "flying": "Terbang", "psychic": "Psikis", "bug": "Serangga",
    "rock": "Batu", "ghost": "Hantu", "dragon": "Naga", "dark": "Gelap",
    "steel": "Baja", "fairy": "Peri",
}

def rs_str(s: str) -> str:
    # Rust string literal: JSON escaping (\" and \\) is compatible; keep UTF-8 raw.
    return json.dumps(s, ensure_ascii=False)

# ---- Questions ----
with open(os.path.join(ROOT, "assets/questions.json"), encoding="utf-8") as f:
    qdata = json.load(f)["questions"]

assert len(qdata) == 120, f"expected 120 questions, got {len(qdata)}"
cats = {}
for q in qdata:
    assert len(q["options"]) == 4, q["question"]
    assert 0 <= q["answer"] < 4, q["question"]
    assert q["difficulty"] in ("mudah", "sedang", "sulit"), q["question"]
    cats.setdefault(q["category"], {}).setdefault(q["difficulty"], 0)
    cats[q["category"]][q["difficulty"]] += 1
for c, d in cats.items():
    assert len(d) == 3 and sum(d.values()) == 20, f"{c}: {d}"
print("questions OK:", len(qdata), "categories:", {c: sum(d.values()) for c, d in cats.items()})

diff_n = {"mudah": 0, "sedang": 1, "sulit": 2}
lines = ["// Generated by tools/gen_data.py — DO NOT EDIT BY HAND.",
         "// Source: assets/questions.json (bank soal Bahasa Indonesia, offline).",
         "",
         "pub struct Question {",
         "    pub category: &'static str,",
         "    pub difficulty: u8, // 0=mudah, 1=sedang, 2=sulit",
         "    pub text: &'static str,",
         "    pub options: [&'static str; 4],",
         "    pub answer: usize,",
         "}",
         "",
         "pub static QUESTIONS: &[Question] = &["]
for q in qdata:
    opts = ", ".join(rs_str(o) for o in q["options"])
    lines.append(f'    Question {{ category: {rs_str(q["category"])}, difficulty: {diff_n[q["difficulty"]]}, text: {rs_str(q["question"])}, options: [{opts}], answer: {q["answer"]} }},')
lines.append("];")
os.makedirs(os.path.join(ROOT, "src"), exist_ok=True)
with open(os.path.join(ROOT, "src/questions_data.rs"), "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")

# ---- Pokemon ----
pokes = []
for pid in range(1, 152):
    with open(f"/tmp/poke/detail/{pid}.json", encoding="utf-8") as f:
        d = json.load(f)
    assert d["id"] == pid, pid
    types = [TYPE_ID[t["type"]["name"]] for t in sorted(d["types"], key=lambda t: t["slot"])]
    pokes.append({
        "id": pid,
        "name": d["name"],
        "types": " & ".join(types),
        "height_m": d["height"] / 10.0,
        "weight_kg": d["weight"] / 10.0,
    })
assert len(pokes) == 151
assert [p["id"] for p in pokes] == list(range(1, 152))
print("pokemon OK: 151, e.g.", pokes[0], "|", pokes[24], "|", pokes[150])

lines = ["// Generated by tools/gen_data.py — DO NOT EDIT BY HAND.",
         "// Source: PokeAPI (nama, tipe, tinggi, berat Gen 1). Tipe diterjemahkan ke Bahasa Indonesia.",
         "// Sprite PNG dibundel di assets/pokemon/<id>.png (bukan dari data ini).",
         "",
         "pub struct Pokemon {",
         "    pub id: u32,",
         "    pub name: &'static str,",
         "    pub types: &'static str, // Bahasa Indonesia, mis. \"Api & Terbang\"",
         "    pub height_m: f32,",
         "    pub weight_kg: f32,",
         "}",
         "",
         "pub static POKEMON: &[Pokemon] = &["]
for p in pokes:
    lines.append(f'    Pokemon {{ id: {p["id"]}, name: {rs_str(p["name"])}, types: {rs_str(p["types"])}, height_m: {p["height_m"]:.1f}, weight_kg: {p["weight_kg"]:.1f} }},')
lines.append("];")
with open(os.path.join(ROOT, "src/pokemon_data.rs"), "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")

# ---- Sprites ----
bad = []
for pid in range(1, 152):
    p = os.path.join(ROOT, "assets/pokemon", f"{pid}.png")
    with open(p, "rb") as f:
        magic = f.read(8)
    if magic != b"\x89PNG\r\n\x1a\n":
        bad.append(pid)
assert not bad, f"bad PNGs: {bad}"
total = sum(os.path.getsize(os.path.join(ROOT, "assets/pokemon", f"{i}.png")) for i in range(1, 152))
print(f"sprites OK: 151 PNG valid, total {total} bytes")
print("DONE")
